export function searchHelpSections(query: string): readonly HelpSection[] {
  const terms = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
  if (!terms.length) return helpSections;
  return helpSections.filter((section) => {
    const text = [section.title, section.summary, ...section.rules.flatMap((rule) => [rule.title, rule.text]), ...section.fields.flat()].join(" ").toLocaleLowerCase();
    return terms.every((term) => text.includes(term));
  });
}
